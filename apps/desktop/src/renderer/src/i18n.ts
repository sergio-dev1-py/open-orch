export type TranslationKey = keyof (typeof dictionaries)["es"]

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const language = state.config?.language ?? "es"
  const dictionary = dictionaries[language] ?? dictionaries.es
  let text: string = dictionary[key] ?? dictionaries.en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** Localized label for a reasoning variant id (falls back to the raw id). */
export function variantLabel(value: string): string {
  if (value === "default") return t("composer.default")
  const key = `variant.${value}` as TranslationKey
  const translated = t(key)
  return translated === key ? value : translated
}
